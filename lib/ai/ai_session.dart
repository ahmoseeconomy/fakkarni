/// اللي القارئ محتاجه عشان ينادي دالتنا `ai-read` — ومفيش حاجة تانية.
///
/// من بعد C2 التطبيق **ما عندوش مفتاح Gemini خالص**: المفتاح سر عند دالة
/// السحابة، والقراية بتتنسب لجلسة المستخدم وبتتحسب عليه. فاللي بيتبعت هو
/// توكن الجلسة، والمفتاح المنشور بتاع المشروع (اللي أصلاً في كل طلب لـSupabase
/// ومش سر).
///
/// واجهة عشان `lib/ai/` ما يستوردش Supabase — التنفيذ في
/// `lib/data/auth/supabase_ai_session.dart`، والاختبارات بتدّي واحدة مزيّفة.
abstract interface class AiSession {
  /// `$SUPABASE_URL/functions/v1/ai-read`
  Uri get endpoint;

  /// المفتاح المنشور بتاع المشروع — header الـ`apikey` اللي البوابة بتطلبه.
  String get publishableKey;

  /// توكن الجلسة الحالي، متجدّد لو كان منتهي. null = مفيش جلسة — والقارئ
  /// ساعتها ما بيبعتش أي طلب.
  Future<String?> accessToken();
}
