/// جنس المريض — عشان الكلام اللي بيخاطبه يطلع صح: «بتفطر» ولا «بتفطري».
///
/// `m` = راجل، `f` = ست. متخزّن بالحرف ده في `patients.sex`. null = لسه ما
/// اتسألش (أجهزة قبل نسخة ٨) — والنص بيرجع للمذكّر اللي كان عليه قبل كده.
enum Sex { m, f }

/// اختيار الكلمة حسب الجنس. [female] بيتاخد لما الجنس `f` بس.
///
/// دارت نقية — مفيش Flutter. الطبقة دي هي المكان الوحيد اللي بيتقرر فيه
/// التذكير والتأنيث؛ الشاشات بتنده `say.pick(...)` أو الجمل الجاهزة تحت
/// بدل ما كل شاشة تكتب `if (sex == Sex.f)` لوحدها.
class Say {
  const Say(this.sex, {this.aboutSomeoneElse = false});

  final Sex? sex;

  /// D4 المسار «بظبّط لحد تاني»: اللي ماسك التليفون بيجاوب **عن** المريض،
  /// فأسئلة الإعداد بالغايب («بيفطر / بتفطر الساعة كام؟»). مش متخزّن — بعد
  /// الإعداد التطبيق بيكلّم المريض نفسه بالمخاطب، لأنه هو اللي هيمسك التليفون.
  final bool aboutSomeoneElse;

  bool get _female => sex == Sex.f;

  String pick(String male, String female) => _female ? female : male;

  /// المخاطب (ذكر / أنثى) أو الغايب (هو / هي).
  String _setup(String you, String youF, String he, String she) =>
      aboutSomeoneElse ? pick(he, she) : pick(you, youF);

  // ---- أسئلة «ظبّط يومك»
  String get wakeQuestion =>
      _setup('بتصحى الساعة كام؟', 'بتصحي الساعة كام؟', 'بيصحى الساعة كام؟', 'بتصحى الساعة كام؟');
  String get breakfastQuestion =>
      _setup('بتفطر الساعة كام؟', 'بتفطري الساعة كام؟', 'بيفطر الساعة كام؟', 'بتفطر الساعة كام؟');
  String get lunchQuestion =>
      _setup('بتتغدى الساعة كام؟', 'بتتغدّي الساعة كام؟', 'بيتغدى الساعة كام؟', 'بتتغدى الساعة كام؟');
  String get dinnerQuestion =>
      _setup('بتتعشى الساعة كام؟', 'بتتعشّي الساعة كام؟', 'بيتعشى الساعة كام؟', 'بتتعشى الساعة كام؟');
  String get sleepQuestion =>
      _setup('بتنام الساعة كام؟', 'بتنامي الساعة كام؟', 'بينام الساعة كام؟', 'بتنام الساعة كام؟');

  /// ده كلام اللي ماسك التليفون عن نفسه. في مسار «لحد تاني» جنسه مش
  /// معروف (الجنس المختار جنس المريض)، فبيفضل بالصيغة العامة.
  String get notSure => aboutSomeoneElse ? 'مش متأكد' : pick('مش متأكد', 'مش متأكدة');

  String get wakeHint => _setup(
        'يومك بيبدأ من هنا — كل المواعيد بتترتب عليه.',
        'يومك بيبدأ من هنا — كل المواعيد بتترتب عليه.',
        'يومه بيبدأ من هنا — كل المواعيد بتترتب عليه.',
        'يومها بيبدأ من هنا — كل المواعيد بتترتب عليه.',
      );
  String get dinnerHint => _setup(
        'لو بتتعشى بدري أو متأخر، اظبطها هنا.',
        'لو بتتعشى بدري أو متأخر، اظبطها هنا.',
        'لو بيتعشى بدري أو متأخر، اظبطها هنا.',
        'لو بتتعشى بدري أو متأخر، اظبطها هنا.',
      );
  String get sleepHint => _setup(
        'لو بتنام بعد نص الليل، اختار من بدري الصبح.',
        'لو بتنام بعد نص الليل، اختار من بدري الصبح.',
        'لو بينام بعد نص الليل، اختار من بدري الصبح.',
        'لو بتنام بعد نص الليل، اختار من بدري الصبح.',
      );
  String get routineTitle =>
      _setup('خلينا نعرف يومك', 'خلينا نعرف يومك', 'خلينا نعرف يومه', 'خلينا نعرف يومها');
  String get routineSubtitle => _setup(
        'خمس أسئلة — وبعدها أي روشتة هتتظبط لوحدها على مواعيدك.',
        'خمس أسئلة — وبعدها أي روشتة هتتظبط لوحدها على مواعيدك.',
        'خمس أسئلة — وبعدها أي روشتة هتتظبط لوحدها على مواعيده.',
        'خمس أسئلة — وبعدها أي روشتة هتتظبط لوحدها على مواعيدها.',
      );

  // ---- الرئيسية
  String get whatNow => pick('تعمل إيه دلوقتي؟', 'تعملي إيه دلوقتي؟');

  // ---- التنبيه والسكة: الحالة اللي التطبيق بيقولها له / لها
  /// «أخدته ٨:٠٠ ص» — التطبيق بيقول للمريض إنه خده.
  String takenAt(String time) => pick('أخدته $time', 'أخدتيه $time');
  String get tookItAlready => pick('خدته خلاص', 'خدتيه خلاص');
  String get forgotIt => pick('نسيتها؟', 'نسيتيها؟');
  String get thanks => pick('تسلم.', 'تسلمي.');
  String get backToDay => pick('ارجع ليومك', 'ارجعي ليومك');
  String get allDone =>
      pick('خلصت أدوية النهاردة كلها. تسلم.', 'خلّصتي أدوية النهاردة كلها. تسلمي.');
}
