/// إعادة التنبيه — دارت نقي، من غير إشعارات ولا قاعدة بيانات.
///
/// التذكير رنّ مرة واحدة ومحدش لمسه. على iOS الإشعار بيدق ثانية ويسكت،
/// والمختبِر قال «مش بيرن». الحل مش تذكير أعلى — السلّم موجود لكده —
/// لكن تذكير **بيتكرر** لحد ما حد يتصرّف:
///
/// | بعد   | إيه                                    |
/// |-------|----------------------------------------|
/// | ٠     | تذكير الجرعة                            |
/// | +٥    | إعادة ١ — نفس التذكير، نفس الأزرار       |
/// | +١٠   | إعادة ٢                                  |
/// | +١٥   | إعادة ٣ — **بتتشال لو درجة +١٥ شغّالة**  |
/// | +١٥   | الدرجة الأولى من السلّم (زي ما هي)        |
/// | +٣٠   | الدرجة التانية (زي ما هي)                 |
///
/// **الإعادة مش درجة على السلّم، ومش بتلمسه.** السلّم بيقول «لسه ما
/// أخدتش؟» بنغمة أعلى وبيهزّ، وبعده السيرفر بيبلّغ ابنه عند +٦٠. الإعادة
/// بتقول نفس جملة التذكير الأصلي تاني — عشان اللي ما سمعش أول مرة يسمع
/// تاني. الأرقام هنا تشغيلية مش طبية، والقاعدة الخامسة فوقها كلها:
/// «أخدته» أو «فكّرني بعدين» بيلغوا كل إعادة لسه ما رنّتش، فوراً.
library;

/// المسافة بين كل إعادة واللي بعدها — من معاد الجرعة **الأصلي**.
const Duration repeatEvery = Duration(minutes: 5);

/// أقصى عدد إعادات لتذكير واحد.
const int maxRepeats = 3;

/// إعادة تنبيه في وقتها الحقيقي.
class RepeatStep {
  const RepeatStep({required this.index, required this.at});

  /// ٠ = أول إعادة (+٥)، ١ = التانية (+١٠)، ٢ = التالتة (+١٥).
  final int index;

  /// إمتى بترنّ.
  final DateTime at;

  /// المسافة من معاد الجرعة الأصلي.
  Duration get delay => repeatEvery * (index + 1);

  @override
  String toString() => 'RepeatStep($index @ $at)';
}

/// كل الإعادات لتذكير معاده [reminderAt] — بالترتيب، من غير أي فلتر.
///
/// المُنشئ بالدقايق مش `.add(Duration)`: مصر بتغيّر التوقيت الصيفي،
/// والمُنشئ بيحسب بالساعة اللي على الحيطة زي باقي المحرك.
List<RepeatStep> repeatsFor(DateTime reminderAt) => [
      for (var i = 0; i < maxRepeats; i++)
        RepeatStep(
          index: i,
          at: DateTime(
            reminderAt.year,
            reminderAt.month,
            reminderAt.day,
            reminderAt.hour,
            reminderAt.minute + repeatEvery.inMinutes * (i + 1),
          ),
        ),
    ];
