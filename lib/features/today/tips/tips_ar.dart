/// دوا مدته بتخلص خلال أيام — «فاضله يومين».
///
/// [daysLeft] من ٠ لـ٣: ٠ = النهارده آخر يوم.
String durationEndingTip(String name, int daysLeft) {
  final left = switch (daysLeft) {
    0 => 'النهارده آخر يوم فيه',
    1 => 'فاضله يوم واحد',
    2 => 'فاضله يومين',
    _ => 'فاضله ${arabicNumber(daysLeft)} أيام',
  };
  return 'دوا $name $left — لو محتاج تكمّله كلّم دكتورك.';
}

/// [days] أيام ورا بعض كل الجرعات فيها اتاخدت — من ٣ وفوق.
String streakTip(int days) => switch (days) {
      2 => 'يومين ورا بعض كل جرعاتك اتاخدت في معادها — كمّل كده.',
      _ => '${arabicNumber(days)} أيام ورا بعض كل جرعاتك اتاخدت في معادها — كمّل كده.',
    };

/// جرعات المسا اتأخّرت أو فاتت أكتر من مرة الأسبوع ده.
const String eveningLateTip =
    'جرعات المسا فاتت أو اتأخّرت أكتر من مرة الأسبوع ده — خلّي الموبايل جنبك وقتها، ولو الميعاد نفسه صعب اسأل دكتورك.';

/// سطر التعليمات اللي المستخدم كتبها بنفسه — «تعليماتك لـ{name}: …».
String instructionsLine(String name, String instructions) => 'تعليماتك لـ$name: $instructions';

/// كل الجمل اللي الاختبار بيقراها — النصايح الثابتة والقوالب بعيّنات.
List<String> allTipTexts() => [
      for (final tips in purposeTips.values)
        for (final t in tips) ...[t, t.replaceAll('{name}', 'Concor')],
      ...generalTips,
      for (var d = 0; d <= 3; d++) durationEndingTip('Augmentin', d),
      for (var d = 2; d <= 10; d++) streakTip(d),
      eveningLateTip,
    ];
