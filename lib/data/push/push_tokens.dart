/// توكن الدفع — السلك الوحيد اللي التنبيه بيوصل لابنه عليه.
///
/// الدرجة الأخيرة في السلّم بتنتهي عند إشعار على موبايل الابن (المكالمات
/// الصوتية اتلغت من المنتج — «دين تقني»). يعني من غير توكن مسجّل، كل
/// اللي فوق ده — الفحص، المهلة، الحجز — بيوصل لـ`no_token` وبيقف.
///
/// Firebase بيفضل **ورا الملفات دي** بالظبط زي ما Supabase ورا
/// `lib/data/auth/`: باقي التطبيق بيشوف [PushTokens] وبس، والاختبارات
/// بتشغّل المنطق كله من غير ما تلمس Firebase ولا مرة.
///
/// التقسيمة تلاتة عشان المنطق يفضل قابل للاختبار:
///   * [DeviceTokenSource] — الجهاز: هات التوكن، وقول لي لما يتغيّر.
///     (Firebase هنا وبس.)
///   * [PushTokenRemote] — السحابة: احجز التوكن ده لصاحبه، أو شيله.
///     (Supabase هنا وبس.)
///   * [PushTokens] — القرار: إمتى نسجّل وإمتى نمسح. دارت خالص.
library;

/// منصّة الجهاز زي ما `device_tokens.platform` بيعرفها — نفس النصّين
/// بالحرف، عشان الـcheck constraint في SQL ما يرفضش.
enum PushPlatform { android, ios }

/// اللي باقي التطبيق بيشوفه.
abstract interface class PushTokens {
  /// بيبدأ السماع: تسجيل مع كل دخول، وإعادة تسجيل مع كل تدوير للتوكن.
  ///
  /// آمن إنه يتنده مرة واحدة عند الإقلاع. مش بيرمي أبداً.
  void start();

  /// تسجيل فوري — بيتنده بعد الربط مباشرة عشان الابن ما يستناش فتحة جاية.
  Future<void> registerNow();

  /// **لازم تتنده قبل `signOut()`، مش بعده.**
  ///
  /// مسح الصف محتاج التوكن بتاع الجلسة الحالية؛ بعد الخروج مفيش صلاحية
  /// والصف بيفضل في السحابة، فتنبيهات مريض غريب تكمّل توصل لموبايل خرج
  /// من حسابه. الترتيب ده هو كل الحكاية.
  Future<void> clear();

  Future<void> dispose();
}

/// الجهاز: منين التوكن وإمتى بيتغيّر.
abstract interface class DeviceTokenSource {
  PushPlatform get platform;

  /// بيطلب إذن الإشعارات لو لسه ما اتطلبش.
  ///
  /// مهم على موبايل **الابن** تحديداً: هو ممكن يكون عدّى على استبدال
  /// الكود من غير ما يعدّي على أسئلة الروتين، فالإذن ما اتطلبش منه ولا
  /// مرة. بيرجّع false لو اترفض — وساعتها بنسجّل التوكن برضه (شوف
  /// [PushTokens]).
  Future<bool> ensurePermission();

  /// null لو Firebase مش متظبط أو الجهاز مش قادر يجيب توكن.
  Future<String?> token();

  /// التوكن بيتغيّر من نفسه: استرجاع نسخة احتياطية، تنضيف بيانات، أو
  /// قرار من Firebase. من غير السماع ده الصف السحابي بيبقى بايت في صمت.
  Stream<String> get refreshes;
}

/// السحابة: مين صاحب التوكن ده.
abstract interface class PushTokenRemote {
  /// `public.claim_device_token` — بوابة واحدة، بتعيد ربط التوكن لصاحبه
  /// الحالي ذرّياً. مش upsert عادي عن قصد (السبب في `0006_push.sql`).
  Future<void> claim(String token, PushPlatform platform);

  /// بيشيل الصف. بيتنده قبل الخروج وبس.
  Future<void> remove(String token);
}
