/// جهة اتصال **واحدة** زي ما الشخص اختارها من شاشة النظام.
///
/// الاسم والرقم وبس. **صلة القرابة مش هنا عن قصد**: الموبايل ما بيعرفش إن
/// ده ابنه ولا دكتوره، واختراعها تخمين على ناس. بتتكتب بإيده زي ما كانت.
class PickedContact {
  const PickedContact({required this.name, required this.phone});

  final String name;
  final String phone;
}

/// النظام رفض يفتح المنتقي (إذن مرفوض، أو مفيش تطبيق جهات اتصال).
///
/// مش خطأ في التطبيق ومش حاجة نعيد المحاولة فيها لوحدنا: الشاشة بتقول
/// جملة واحدة، والكتابة بالإيد شغّالة زي ما هي.
class ContactPickerDenied implements Exception {
  const ContactPickerDenied();
}

/// **بنقرا الجهة اللي المنتقي رجّعها وبس.**
///
/// الواجهة دي مالهاش أي دالة بتعدّد دفتر العناوين، ولا هتبقى ليها: التطبيق
/// عمره ما بيقرا جهات الاتصال — بيفتح شاشة النظام، والشخص بيختار واحدة،
/// وإحنا بناخد اسمها ورقمها. اللي بيتخزّن هو الاتنين دول بس، وعمرهم ما
/// بيتبعتوا لحد (الأرقام مش في المزامنة ومفيش لها عمود في السحابة).
///
/// واجهة عشان الشاشة تتختبر من غير نظام تشغيل — زي `AuthService` و
/// `PlacesSource` بالظبط.
abstract interface class ContactPicker {
  /// بيفتح شاشة النظام. `null` = الشخص قفلها من غير ما يختار (سكوت، مش خطأ).
  /// بيرمي [ContactPickerDenied] لو النظام رفض يفتحها أصلاً.
  Future<PickedContact?> pickOne();
}
