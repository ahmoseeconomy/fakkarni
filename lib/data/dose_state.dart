/// حالة جرعة في يوم معيّن.
///
/// الجرعة المتاخدة بتفضل في القايمة — بتهدى بس، ما بتتمسحش. المريض لازم
/// يشوف إنه خد الدوا، مش يلاقي السطر اختفى ويشك إنه نسي.
enum DoseState {
  pending,
  taken,
  skipped,
  missed,

  /// القاعدة اتغيّرت والجرعة دي بقت قبل سريانها — **مش** «اتنست» ولا قرار
  /// من المريض. بتتكتب بدل المسح عشان السحابة مفيهاش مسح (دين ١): صف
  /// اتمسح محلي كان هيفضل pending هناك والسيرفر ينبّه ابنه عن جرعة مش
  /// موجودة. «يومك» والتقويم وشاشة الابن ما بيعرضوهاش.
  superseded,
}
